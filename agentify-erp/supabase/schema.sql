  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, receipt_no TEXT UNIQUE NOT NULL, date TEXT NOT NULL, contact_id BIGINT NOT NULL REFERENCES contacts(id),
  sale_id BIGINT REFERENCES sales(id), project_id BIGINT, property_id BIGINT,
