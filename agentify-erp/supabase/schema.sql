  features TEXT DEFAULT '{}', amenities TEXT DEFAULT '[]', short_desc TEXT, description TEXT,
  videos TEXT DEFAULT '[]', agent_id BIGINT REFERENCES users(id), contact_email TEXT, contact_phone TEXT, contact_whatsapp TEXT,
  status TEXT NOT NULL DEFAULT 'draft', review_state TEXT NOT NULL DEFAULT 'draft', published BIGINT NOT NULL DEFAULT 0,
  dev_status TEXT, reserved_contact_id BIGINT, is_demo BIGINT NOT NULL DEFAULT 0, created_by BIGINT, created_at TEXT NOT NULL, updated_at TEXT, file_no TEXT, registration_no TEXT, file_status TEXT, file_notes TEXT);

CREATE TABLE IF NOT EXISTS sales(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, sale_no TEXT UNIQUE NOT NULL, kind TEXT NOT NULL DEFAULT 'property', title TEXT,
  contact_id BIGINT NOT NULL REFERENCES contacts(id),
  property_id BIGINT REFERENCES properties(id), project_id BIGINT REFERENCES projects(id),
  bundle_id BIGINT, linked_sale_id BIGINT,
  sale_date TEXT NOT NULL, sale_price BIGINT NOT NULL, discount BIGINT NOT NULL DEFAULT 0, net_price BIGINT NOT NULL,
  booking_amount BIGINT NOT NULL DEFAULT 0, advance_amount BIGINT NOT NULL DEFAULT 0,
  num_installments BIGINT NOT NULL DEFAULT 0, installment_amount BIGINT NOT NULL DEFAULT 0,
