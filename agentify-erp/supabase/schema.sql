  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, emp_code TEXT UNIQUE, name TEXT NOT NULL, cnic TEXT, dob TEXT, gender TEXT, phone TEXT, email TEXT,
