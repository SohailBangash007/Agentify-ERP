CREATE TABLE IF NOT EXISTS installments(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, sale_id BIGINT NOT NULL REFERENCES sales(id) ON DELETE CASCADE, seq BIGINT NOT NULL,
  kind TEXT NOT NULL, due_date TEXT NOT NULL, amount BIGINT NOT NULL, paid BIGINT NOT NULL DEFAULT 0,
  status TEXT NOT NULL DEFAULT 'pending', paid_date TEXT);

CREATE TABLE IF NOT EXISTS accounts(
