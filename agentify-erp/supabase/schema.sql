CREATE TABLE IF NOT EXISTS vendors(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, company TEXT, phone TEXT, email TEXT, address TEXT, cnic_tax TEXT,
