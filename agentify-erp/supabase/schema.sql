-- Postgres schema for Supabase, generated from the app's SQLite schema (server/src/db.js).
-- Run in the Supabase SQL editor, or: psql "$DATABASE_URL" -f supabase/schema.sql
-- Integers are BIGINT (PKR amounts), booleans stay 0/1 integers, timestamps stay PKT text, exactly as the app writes them.

CREATE TABLE IF NOT EXISTS counters(key TEXT PRIMARY KEY, value BIGINT NOT NULL DEFAULT 0);

CREATE TABLE IF NOT EXISTS settings(key TEXT PRIMARY KEY, value TEXT);

CREATE TABLE IF NOT EXISTS roles(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT UNIQUE NOT NULL, description TEXT,
  own_scope BIGINT NOT NULL DEFAULT 0, portal BIGINT NOT NULL DEFAULT 0, is_system BIGINT NOT NULL DEFAULT 0);

CREATE TABLE IF NOT EXISTS role_permissions(
  role_id BIGINT NOT NULL REFERENCES roles(id) ON DELETE CASCADE, module TEXT NOT NULL, action TEXT NOT NULL,
  PRIMARY KEY(role_id,module,action));

CREATE TABLE IF NOT EXISTS users(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, email TEXT UNIQUE, phone TEXT, password_hash TEXT NOT NULL,
  role_id BIGINT NOT NULL REFERENCES roles(id), active BIGINT NOT NULL DEFAULT 1,
  contact_id BIGINT, token_version BIGINT NOT NULL DEFAULT 0, is_demo BIGINT NOT NULL DEFAULT 0,
  last_login TEXT, created_at TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS lookups(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, type TEXT NOT NULL, value TEXT NOT NULL, color TEXT, meta TEXT,
  sort_order BIGINT NOT NULL DEFAULT 0, active BIGINT NOT NULL DEFAULT 1);

CREATE TABLE IF NOT EXISTS custom_fields(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, entity TEXT NOT NULL, label TEXT NOT NULL, key TEXT NOT NULL,
  type TEXT NOT NULL DEFAULT 'text', options TEXT, required BIGINT NOT NULL DEFAULT 0, sort_order BIGINT NOT NULL DEFAULT 0,
  UNIQUE(entity,key));

CREATE TABLE IF NOT EXISTS contacts(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name TEXT, last_name TEXT, full_name TEXT NOT NULL, father_name TEXT, cnic TEXT, dob TEXT, gender TEXT,
  phone TEXT, alt_phone TEXT, whatsapp TEXT, email TEXT,
  country TEXT DEFAULT 'Pakistan', province TEXT, city TEXT, area TEXT, address TEXT, company TEXT,
  lead_source TEXT, stage_id BIGINT REFERENCES lookups(id), lead_type TEXT,
  agent_id BIGINT REFERENCES users(id), manager_id BIGINT REFERENCES users(id),
  tags TEXT DEFAULT '[]', priority TEXT DEFAULT 'Medium',
  project_id BIGINT, property_id BIGINT, budget BIGINT, pref_location TEXT, property_type TEXT,
  followup_date TEXT, is_customer BIGINT NOT NULL DEFAULT 0, customer_since TEXT,
  custom TEXT DEFAULT '{}', is_demo BIGINT NOT NULL DEFAULT 0,
  created_by BIGINT, created_at TEXT NOT NULL, updated_at TEXT, last_activity_at TEXT, customer_code TEXT);

CREATE TABLE IF NOT EXISTS activities(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, contact_id BIGINT, entity_type TEXT, entity_id BIGINT, user_id BIGINT, user_name TEXT,
  action TEXT NOT NULL, field TEXT, prev_value TEXT, new_value TEXT, detail TEXT, created_at TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS notes(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, entity_type TEXT NOT NULL DEFAULT 'contact', entity_id BIGINT NOT NULL, body TEXT NOT NULL,
  user_id BIGINT, created_at TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS tasks(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, entity_type TEXT NOT NULL DEFAULT 'contact', entity_id BIGINT, title TEXT NOT NULL,
  due_date TEXT, assigned_to BIGINT, status TEXT NOT NULL DEFAULT 'open', priority TEXT DEFAULT 'Medium',
  created_by BIGINT, completed_at TEXT, created_at TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS documents(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, entity_type TEXT NOT NULL, entity_id BIGINT NOT NULL, category TEXT, name TEXT NOT NULL,
  path TEXT NOT NULL, mime TEXT, size BIGINT, portal_visible BIGINT NOT NULL DEFAULT 0, uploaded_by BIGINT, created_at TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS media(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, entity_type TEXT NOT NULL, entity_id BIGINT NOT NULL, kind TEXT NOT NULL,
  path TEXT NOT NULL, caption TEXT, sort_order BIGINT NOT NULL DEFAULT 0, created_at TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS smart_lists(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL, logic TEXT NOT NULL DEFAULT 'AND', rules TEXT NOT NULL DEFAULT '[]',
  owner_id BIGINT, shared BIGINT NOT NULL DEFAULT 0, is_default BIGINT NOT NULL DEFAULT 0, created_at TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS projects(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code TEXT UNIQUE NOT NULL, name TEXT NOT NULL, location TEXT, developer TEXT, description TEXT,
  total_land_area DOUBLE PRECISION, land_unit TEXT DEFAULT 'Kanal', total_units BIGINT, total_value BIGINT,
  dev_status TEXT DEFAULT 'Planning', manager_id BIGINT REFERENCES users(id), start_date TEXT, expected_completion TEXT,
  is_development BIGINT NOT NULL DEFAULT 1, kind TEXT NOT NULL DEFAULT 'development', budget BIGINT, site_visible BIGINT NOT NULL DEFAULT 1, is_demo BIGINT NOT NULL DEFAULT 0, created_at TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS dev_items(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE, name TEXT NOT NULL,
  progress BIGINT NOT NULL DEFAULT 0, sort_order BIGINT NOT NULL DEFAULT 0);

CREATE TABLE IF NOT EXISTS dev_updates(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, project_id BIGINT NOT NULL REFERENCES projects(id) ON DELETE CASCADE, update_date TEXT NOT NULL,
  title TEXT NOT NULL, kind TEXT DEFAULT 'Progress', progress BIGINT, description TEXT, videos TEXT DEFAULT '[]',
  published BIGINT NOT NULL DEFAULT 1, created_by BIGINT, created_at TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS properties(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code TEXT UNIQUE, title TEXT NOT NULL, purpose TEXT NOT NULL DEFAULT 'Sell',
  property_type TEXT, project_id BIGINT REFERENCES projects(id), block TEXT, sector TEXT, plot_no TEXT,
  city TEXT, area_name TEXT, location TEXT, address TEXT, lat DOUBLE PRECISION, lng DOUBLE PRECISION,
  area_size DOUBLE PRECISION, unit TEXT DEFAULT 'Marla', total_price BIGINT NOT NULL DEFAULT 0, price_per_unit BIGINT,
  discount BIGINT NOT NULL DEFAULT 0, net_price BIGINT NOT NULL DEFAULT 0,
