  project_id BIGINT, reversal_of BIGINT, created_by BIGINT, created_at TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS journal_lines(
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, journal_id BIGINT NOT NULL REFERENCES journals(id) ON DELETE CASCADE,
